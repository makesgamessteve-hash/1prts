-- Lua unit tests: the interaction prompt, the touch overlay, sessions and settings. MIT License.
local hud = require("ui.hud")
local touch = require("ui.touch")
local session = require("game.session")
local settings = require("game.settings")

-- In front of the keep's door, looking at it (beside the test walls of test_build.lua).
local function face_the_door() prts.commander.spawn{ pos = { -0.5, 0.2, 11 }, yaw = 0 } end

T.case("the prompt names the action and the key of the active scheme", function()
  face_the_door()
  T.ui_frame()
  T.eq(prts.commander.target() ~= nil, true, "the door is in view")
  T.eq(hud.prompt(), "[E] Open door")
  T.is_true(T.ui_has("[E] Open door"), "drawn")
  T.scheme("gamepad")
  T.ui_frame()
  T.eq(hud.scheme, "gamepad", "scheme-changed event")
  T.is_true(T.ui_has("(X) Open door"), "gamepad prompt")
  T.scheme("kbm")
  T.ui_frame()
  hud.visible = false
  T.eq(hud.draw(640, 360), false)
  hud.visible = true
  prts.ui.set_modal(true)
  T.eq(hud.draw(640, 360), false, "hidden under menus")
  prts.ui.set_modal(false)
  prts.commander.spawn{ pos = { 0, 0.2, 40 }, yaw = 0 }
  T.eq(hud.prompt(), nil, "nothing in view")
  T.eq(hud.draw(640, 360), false)
end)

T.case("prompt texts by kind of object", function()
  local door = prts.entity.find("keep.door")
  T.eq(hud.prompt_text(door), prts.entity.data(door).open and "Close door" or "Open door")
  T.eq(hud.prompt_text(prts.entity.find("keep.lift.lever")), "Pull the lever")
  T.eq(hud.prompt_text(prts.entity.find("keep.lift.call0")), "Call the lift")
  local bell = prts.entity.spawn{ name = "bell", usable = true }
  prts.entity.data(bell).prompt = "Ring the bell"
  T.eq(hud.prompt_text(bell), "Ring the bell")
  T.eq(hud.prompt_text(prts.entity.spawn{ name = "thing", usable = true }), "Use")
end)

T.case("touch overlay: stick, context buttons only when usable", function()
  T.eq(touch.apply(), #touch.LAYOUT.buttons)
  face_the_door()
  T.scheme("touch")
  T.touch(1, 0.25, 0.7, true)
  T.ui_frame()
  T.touch(1, 0.25, 0.4, true)  -- beyond the stick radius: the knob stays on the ring
  T.touch(2, 0.93, 0.74, true) -- holding the jump button
  T.ui_frame(2)
  local state = prts.input.touch_state()
  T.is_true(state.stick ~= nil, "stick shown")
  T.is_true(state.buttons[2].held, "jump held")
  T.is_true(prts.input.down("jump"), "jump pressed by touch")
  T.is_true(T.ui_has("Use"), "use shows: the door is in view")
  T.is_true(T.ui_has("Jump"), "jump shows while playing")
  T.touch(1, 0.25, 0.4, false)
  T.touch(2, 0.93, 0.74, false)
  T.ui_frame()
  prts.ui.set_modal(true)
  local usable = touch.usable()
  T.eq(usable.use or usable.jump, false, "nothing in menus")
  T.eq(touch.draw(640, 360), false)
  prts.ui.set_modal(false)
  T.scheme("kbm")
  T.ui_frame()
  T.eq(touch.draw(640, 360), false, "only for the touch scheme")
  T.eq(T.ui_has("Jump"), false)
end)

T.case("a session starts once", function()
  T.eq(session.current, "proving_ground")
  T.eq(session.start("proving_ground"), false)
end)

T.case("video settings: saved values over defaults, wrong types ignored", function()
  prts.settings.set("video.fog", "yes")
  prts.settings.set("video.dither", false)
  local v = settings.video()
  T.eq(v.fog, true, "wrong type")
  T.eq(v.dither, false, "a saved false")
  T.eq(settings.next_preset("native"), "authentic")
  T.eq(settings.next_preset("bogus"), "authentic")
  settings.set_video("preset", "hd", false)
  T.eq(prts.render.settings().lines, 540)
  prts.settings.set("video", nil)
  settings.apply()
  T.eq(prts.render.settings().preset, "retro")
  T.eq(settings.audio_volume("music"), 1.0)
end)
