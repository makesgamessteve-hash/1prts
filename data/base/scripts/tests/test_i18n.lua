local I = require("lib.i18n")

T.case("languages fall back to English, take mods' strings and fill placeholders", function()
  T.eq(I.set("xx"), "en", "an unknown language is English")
  T.eq(I.t("Options"), "Options")
  T.eq(I.t(42), 42, "not text: as it is")
  T.eq(I.t("{n} objects", { n = 3 }), "3 objects")
  T.eq(I.t("{n} and {m}", { n = 1 }), "1 and {m}", "a missing value stays a placeholder")
  T.eq(I.set("de"), "de")
  T.eq(I.t("Options"), "Optionen")
  I.add("de", { ["A mod's word"] = "Ein Wort" }, { { "^Mod (%d+)$", "Modul %1" } })
  T.eq(I.t("A mod's word"), "Ein Wort")
  T.eq(I.t("Mod 7"), "Modul 7")
  local t = I.add("qq", { Options = "Q-Options" })
  T.eq(t.name, "qq", "a language a mod brings")
  T.eq(I.set("qq"), "qq")
  T.eq(I.t("Options"), "Q-Options")
  T.eq(I.table("zz"), nil, "no such language")
  T.eq(I.install(), false, "installed once at boot")
  I.set("en")
end)
