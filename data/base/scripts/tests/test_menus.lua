-- Lua unit tests: front-end and pause menus, options, controls and credits, driven through
-- the real UI with synchronous frames (T.ui_frame, T.ui_click). MIT License.
local menu = require("ui.menu")
local options = require("ui.options")
local controls = require("ui.controls")
local credits = require("ui.credits")
local settings = require("game.settings")
local session = require("game.session")
local glyphs = require("ui.glyphs")

T.case("the front-end menu offers the map, options, credits and quit", function()
  menu.open("main")
  T.ui_frame()
  T.is_true(prts.ui.modal(), "menus take the pointer")
  T.is_true(T.ui_has("Banner & Bastion"), "title")
  T.is_true(T.ui_has("War through a commander's eyes"), "subtitle")
  for _, label in ipairs({ "Harrowmark", "Options", "Credits", "Quit" }) do T.is_true(T.ui_has(label), label) end
  -- the map is already loaded in test runs: starting another one is refused, the menu stays
  T.ui_click("Harrowmark")
  T.eq(menu.screen, "main")
  -- the other maps are on the Battles screen
  T.ui_click("Battles: skirmish and scenarios")
  T.eq(menu.screen, "battles")
  T.is_true(T.ui_has("Scenario: The Reef War"), "a scenario")
  T.ui_click("Back")
  T.eq(menu.screen, "pause", "back leads to the pause menu while playing")
  menu.open("main")
  T.ui_frame()
  T.ui_click("Credits")
  T.eq(menu.screen, "credits")
  T.is_true(T.ui_has("== Base game =="), "credits list")
  T.ui_click("credits.back")
  T.eq(menu.screen, "pause", "back leads to the pause menu while playing")
  T.ui_click("Resume")
  T.eq(menu.screen, nil)
  T.eq(prts.ui.modal(), false)
end)

T.case("Esc opens and closes menus and goes back one screen", function()
  menu.open(nil)
  T.key("Escape")
  T.eq(menu.screen, "pause", "Esc while playing")
  T.ui_click("Options")
  T.eq(menu.screen, "options")
  T.key("Escape")
  T.eq(menu.screen, "pause", "Esc goes back")
  T.key("Escape")
  T.eq(menu.screen, nil, "Esc closes the pause menu")
  menu.open("main")
  T.eq(menu.on_menu_key(), "main", "the front-end stays")
  menu.open("credits")
  T.eq(menu.on_menu_key(), "pause")
  menu.open(nil)
  local current = session.current
  session.current = nil
  T.eq(menu.on_menu_key(), nil, "nothing to pause without a map")
  T.eq(menu.home(), "main")
  session.current = current
end)

T.case("video options apply at once and are saved", function()
  menu.open("options")
  options.tab = "video"
  T.ui_frame()
  local before = prts.render.settings().preset
  T.ui_click("video.preset")
  T.eq(prts.render.settings().preset, settings.next_preset(before))
  T.eq(prts.settings.get("video.preset"), settings.next_preset(before), "saved")
  local fog = prts.render.settings().fog
  T.ui_click("video.fog")
  T.eq(prts.render.settings().fog, not fog)
  T.ui_click("video.fog")
  T.ui_click("video.fov") -- the middle of the slider
  T.eq(prts.render.settings().fov, 80)
  T.ui_click("options.back")
  T.eq(menu.screen, "pause")
  prts.settings.set("video", nil)
  settings.apply_video()
  prts.settings.save()
  T.eq(prts.render.settings().preset, "retro")
end)

T.case("audio options keep volumes and use the mixer when there is one", function()
  menu.open("options")
  T.ui_click("tab.audio")
  T.eq(options.tab, "audio")
  local had = prts.audio
  prts.audio = false -- a build without the mixer keeps the volumes for later
  T.ui_frame()
  T.is_true(T.ui_has("No audio mixer"), "no mixer in this build")
  local got = {}
  prts.audio = { set_volume = function(bus, v) got[bus] = v end }
  T.ui_frame()
  T.eq(T.ui_has("No audio mixer"), false)
  T.ui_click("audio.music")
  T.near(got.music, 0.5, 0.06)
  T.near(prts.settings.get("audio.music"), 0.5, 0.06)
  T.is_true(settings.apply_audio(), "applied")
  T.near(got.master, 1.0, 1e-9)
  prts.audio = had
  T.eq(settings.apply_audio(), had ~= nil)
  T.eq(settings.set_audio("voice", 0.25), had ~= nil)
  T.eq(settings.audio_volume("voice"), 0.25)
  prts.settings.set("audio", nil)
  options.tab = "video"
  menu.open(nil)
end)

T.case("controls: rebinding by key, Esc cancels, touch cycles, defaults restore", function()
  menu.open("options")
  T.ui_click("tab.controls")
  T.is_true(T.ui_has("Move forward"), "actions are listed")
  T.is_true(T.ui_has("Menu"), "actions defined by other scripts are listed too")
  T.is_true(T.ui_has("W, Up"), "kbm bindings shown")
  -- keyboard: press the new key (rows near the top of the list are on screen)
  T.ui_click("rebind.sprint")
  T.eq(controls.capturing, "sprint")
  T.is_true(T.ui_has("Press the new key or button for Sprint"), "waiting for a key")
  T.key("F")
  T.eq(controls.capturing, nil)
  T.eq(glyphs.list("sprint", "kbm"), "F")
  T.eq(prts.settings.get("bindings.kbm.sprint").keys[1], "F", "override stored")
  -- Esc cancels waiting
  T.ui_click("rebind.crouch")
  T.key("Escape")
  T.eq(controls.capturing, nil)
  T.eq(menu.screen, "options", "Esc only cancelled")
  T.eq(glyphs.list("crouch", "kbm"), "Left Ctrl, C")
  -- gamepad: a button and a stick
  T.ui_click("scheme.gamepad")
  T.eq(controls.scheme, "gamepad")
  T.ui_click("rebind.run")
  T.pad_button(3, true)
  T.ui_frame()
  T.pad_button(3, false)
  T.eq(glyphs.list("run", "gamepad"), "Y")
  T.ui_click("rebind.crouch")
  T.pad_axis(5, 0.9)
  T.ui_frame()
  T.pad_axis(5, 0)
  T.eq(glyphs.list("crouch", "gamepad"), "RT")
  T.ui_click("controls.reset")
  T.eq(glyphs.list("run", "gamepad"), "LS")
  -- touch: Change cycles through the touch controls
  T.ui_click("scheme.touch")
  T.eq(glyphs.list("crouch", "touch"), "Crouch button")
  T.ui_click("rebind.crouch")
  T.eq(glyphs.list("crouch", "touch"), "Run button")
  T.ui_click("rebind.crouch")
  T.eq(glyphs.list("crouch", "touch"), "Map button", "then the commander's tools")
  for _ = 1, 4 do T.ui_click("rebind.crouch") end
  T.eq(glyphs.list("crouch", "touch"), "Next button")
  T.ui_click("rebind.crouch")
  T.eq(glyphs.list("crouch", "touch"), "Ride button")
  T.ui_click("rebind.crouch")
  T.eq(glyphs.list("crouch", "touch"), "none")
  T.ui_click("rebind.crouch")
  T.eq(glyphs.list("crouch", "touch"), "Tap")
  T.ui_click("controls.reset")
  T.eq(glyphs.list("crouch", "touch"), "Crouch button")
  T.ui_click("scheme.kbm")
  T.ui_click("controls.reset")
  T.eq(glyphs.list("sprint", "kbm"), "Left Alt")
  T.eq(prts.settings.get("bindings.kbm"), nil, "override forgotten")
  T.ui_click("options.back")
  menu.open(nil)
  T.eq(controls.cancel(), false)
end)

T.case("a rebound key triggers the action and the old one does not", function()
  prts.input.rebind("use", "kbm", "G")
  T._key("G", true)
  T.ui_frame()
  T.is_true(prts.input.down("use"), "G triggers use")
  T._key("G", false)
  T._key("E", true)
  T.ui_frame()
  T.eq(prts.input.down("use"), false, "E no longer does")
  T._key("E", false)
  prts.input.reset_bindings()
  T.ui_frame()
end)

T.case("credits come from every pack's CREDITS.md and the third-party list", function()
  local rows = credits.parse("| Path | Title |\n|---|---|\n| `a.png` | A | Me | CC0-1.0 | original | none |\n")
  T.eq(#rows, 1)
  T.eq(rows[1].path, "a.png")
  T.eq(rows[1].license, "CC0-1.0")
  T.is_true(credits.refresh() > 20, "lines")
  local text = {}
  for _, l in ipairs(credits.lines) do text[#text + 1] = l.text end
  text = table.concat(text, "\n")
  T.is_true(text:find("Stone wall texture - The Banner & Bastion Contributors (CC-BY-4.0)", 1, true) ~= nil, "base entry")
  T.is_true(text:find("Third-party code", 1, true) ~= nil, "third-party section")
  T.is_true(text:find("Lua 5.4.7 - MIT", 1, true) ~= nil, "Lua")
  T.is_true(text:find("stb_image, stb_image_write - MIT or public domain", 1, true) ~= nil, "stb without version")
end)

