T.case("input: actions, bindings, rebinding and capture", function()
  local actions = prts.input.actions()
  T.eq(actions[1].id, "move_forward")
  T.eq(actions[1].label, "Move forward")
  prts.input.action{ id = "flashlight", keys = { "L" } }
  T.eq(prts.input.actions()[#prts.input.actions()].label, "flashlight", "the id when there is no label")
  local b = prts.input.bindings("use")
  T.eq(b.kbm[1].name, "E")
  T.eq(b.kbm[2].kind, "mouse_button")
  T.eq(b.gamepad[1].code, 2)
  T.eq(b.touch[1].kind, "touch_button")
  T.fails(function() prts.input.bindings("nothing") end)
  T.fails(function() prts.input.rebind("nothing", "kbm", "F") end, "unknown action")
  T.fails(function() prts.input.rebind("use", "xr", {}) end, "xr is not rebindable")
  T.fails(function() prts.input.rebind("use", "kbm", { pad_buttons = { 1 } }) end, "wrong scheme")
  T.fails(function() prts.input.rebind("use", "kbm", "NoSuchKey") end, "bad key")
  T.eq(prts.input.bindings("use").kbm[1].name, "E", "a failed rebind changes nothing")
  T.fails(function() prts.input.rebind("use", "gamepad", { pad_buttons = { 99 } }) end)
  T.fails(function() prts.input.rebind("use", "gamepad", "A") end, "strings are kbm keys only")
  T.is_true(prts.input.rebind("use", "gamepad", { pad_buttons = { 0 } }))
  T.is_true(prts.input.rebind("use", "touch", { touch_buttons = { 1 } }))
  T.is_true(prts.input.rebind("look_x", "gamepad", { pad_axes = { { code = 2, scale = -8 } } }))
  T.eq(prts.input.bindings("look_x").gamepad[1].scale, -8)
  prts.input.reset_bindings("gamepad")
  T.eq(prts.input.bindings("use").gamepad[1].code, 2, "gamepad reset")
  T.eq(prts.input.bindings("use").touch[1].code, 1, "touch kept")
  prts.input.reset_bindings()
  T.eq(prts.input.bindings("use").touch[1].code, 0, "all reset")
  T.fails(function() prts.input.reset_bindings("xr") end)
  T.eq(prts.input.capture("kbm"), nil, "nothing pressed")
  T.eq(prts.input.capture("touch"), nil, "touch is not captured")
  T.eq(prts.input.went_down("use"), false)
  T.fails(function() prts.input.touch_visible("nothing", true) end)
  -- broken saved overrides fall back to the defaults when an action is defined
  prts.settings.set("bindings.kbm.jump", { keys = { "NoSuchKey" } })
  prts.settings.set("bindings.gamepad.jump", { pad_buttons = { 5 } })
  prts.input.action{ id = "jump", label = "Jump", keys = { "Space" }, pad_buttons = { 0 }, touch_buttons = { 2 } }
  T.eq(prts.input.bindings("jump").kbm[1].name, "Space")
  T.eq(prts.input.bindings("jump").gamepad[1].code, 5)
  prts.settings.set("bindings", nil)
  prts.input.reset_bindings()
end)

T.case("app: boot flags, mounts, licenses and the commander's target", function()
  T.eq(prts.boot.auto_start, true)
  T.eq(prts.boot.front_end, false)
  T.eq(prts.boot.test, true)
  T.eq(prts.vfs.mounts()[1].id, "base")
  local names = {}
  for _, l in ipairs(prts.licenses()) do names[#names + 1] = l.name end
  T.is_true(table.concat(names, ","):find("microui", 1, true) ~= nil)
  prts.commander.spawn{ pos = { -0.5, 0.2, 11 }, yaw = 0 }
  local e, name = prts.commander.target()
  T.eq(name, "keep.door")
  T.eq(e, prts.entity.find("keep.door"))
  prts.scene.finish()
  prts.app.quit() -- only asks the frame loop to stop; the test runner carries on
end)

T.case("developer tools exist only in developer builds", function()
  if not prts.boot.developer then
    T.eq(prts.dev, nil)
    return
  end
  T.eq(prts.dev.console(true), true)
  T.ui_frame()
  T.is_true(T.ui_has("Developer console"), "console window")
  prts.dev.run("help")
  local lines = T.console_lines()
  T.is_true(lines[#lines - 1]:find("commands", 1, true) ~= nil, "help")
  T.eq(prts.dev.console(false), false)
  T.eq(prts.dev.observer(true), true)
  T.eq(prts.dev.observer(), true)
  T.ui_frame()
  T.is_true(T.ui_has("DEVELOPER VIEW"), "labeled")
  T.eq(prts.dev.observer(false), false)
end)
