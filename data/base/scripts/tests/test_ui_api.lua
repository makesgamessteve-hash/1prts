-- Runs fn inside one screen frame (as a 'ui' handler) and returns what it returned.
local function in_frame(fn)
  local result
  prts.events.on("ui", "zz.test", function(surface, w, h)
    if surface == "screen" then result = { pcall(fn, w, h) } end
  end)
  T.ui_frame()
  prts.events.off("ui", "zz.test")
  return table.unpack(result)
end

T.case("prts.ui widgets and drawing", function()
  local ok, err = in_frame(function(w, h)
    T.eq(w, 640)
    T.eq(h, 360)
    T.eq(select(1, prts.ui.size()), 640)
    prts.ui.window("Widgets", 10, 10, 300, 200, function()
      prts.ui.row({ 100, -1 }, 0)
      prts.ui.label("left")
      prts.ui.label("centered", true)
      prts.ui.row({ -1 })
      prts.ui.text("a wrapped paragraph of text")
      T.eq(prts.ui.button("Press"), false)
      local v, changed = prts.ui.checkbox("Tick", true, "tick")
      T.eq(v, true)
      T.eq(changed, false)
      local s, moved = prts.ui.slider("amount", 3, 0, 10)
      T.eq(s, 3)
      T.eq(moved, false)
      local text, submitted = prts.ui.textbox("name", "Aldric")
      T.eq(text, "Aldric")
      T.eq(submitted, false)
      T.eq(prts.ui.textbox("empty"), "")
      prts.ui.row({ -1 }, 40)
      prts.ui.panel("inner", function() prts.ui.label("in a panel") end, true)
    end)
    prts.ui.window("Bare", 0, 0, 50, 20, { title = false, frame = false, scroll = false, input = false }, function() end)
    prts.ui.draw_text("hello", 5, 5, { align = "right", scale = 2, color = { 255, 0, 0 } })
    prts.ui.draw_text("plain", 5, 5)
    prts.ui.draw_rect(0, 0, 4, 4, { 10, 20, 30, 40 })
    prts.ui.draw_rect(0, 0, 4, 4)
    prts.ui.draw_icon("ring", 0, 0, 8, 8)
    return "done"
  end)
  T.eq(err, "done")
  T.is_true(ok, "drawn")
  T.is_true(T.ui_has("in a panel"), "texts are recorded")
  T.is_true(T.ui_has("Widgets"), "window titles too")
  T.eq(prts.ui.text_width("ab"), 12)
  T.eq(prts.ui.font().height, 9)
  T.eq(prts.ui.hovered(), false)
end)

T.case("prts.ui reports misuse as script errors", function()
  T.fails(function() prts.ui.label("outside a frame") end, "outside a frame")
  T.fails(function() prts.ui.draw_rect(0, 0, 1, 1) end, "drawing outside a frame")
  T.fails(function() prts.ui.draw_icon("disc", 0, 0, 1, 1) end, "icons outside a frame")
  T.eq(in_frame(function() prts.ui.label("outside a window") end), false)
  T.eq(in_frame(function() prts.ui.draw_icon("nope", 0, 0, 1, 1) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.row({}) end) end), false)
  T.eq(in_frame(function() prts.ui.window("", 0, 0, 10, 10, function() end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.slider("s", 1, 5, 5) end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.text(string.rep("x", 9000)) end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.button(string.rep("x", 2000)) end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.checkbox(string.rep("x", 2000)) end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.textbox(string.rep("x", 2000)) end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() prts.ui.panel(string.rep("x", 2000), print) end) end), false)
  T.eq(in_frame(function() prts.ui.draw_text(string.rep("x", 2000), 0, 0) end), false)
  -- an error inside a window still closes it, and the next frame works
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function() error("inside") end) end), false)
  T.eq(in_frame(function() prts.ui.window("w", 0, 0, 10, 10, function()
    prts.ui.row({ -1 }) prts.ui.panel("p", function() error("in panel") end) end) end), false)
  local depth = 0
  local function nest() depth = depth + 1 prts.ui.window("n" .. depth, 0, 0, 10, 10, nest) end
  T.eq(in_frame(nest), false, "nesting is limited")
  T.eq(in_frame(function() return true end), true)
end)

T.case("world surfaces", function()
  local s = prts.ui.surface{ id = "test_pool", width = 64, height = 32, origin = { 0, 2, 0 }, right = { 1, 0, 0 },
                             down = { 0, -1, 0 } }
  T.is_true(s >= 1, "slot")
  T.eq(prts.ui.surface{ id = "test_pool", width = 64, height = 64 }, s, "same slot when resized")
  T.fails(function() prts.ui.surface{ id = "screen" } end)
  T.fails(function() prts.ui.surface{ width = 8 } end)
  T.fails(function() prts.ui.surface{ id = "tiny", width = 2 } end)
  local seen
  prts.events.on("ui", "zz.surface", function(surface, w, h)
    if surface == "test_pool" then
      seen = w .. "x" .. h
      prts.ui.draw_text("pool", 0, 0)
    end
  end)
  T.ui_frame()
  prts.events.off("ui", "zz.surface")
  T.eq(seen, "64x64")
  T.is_true(T.ui_has("pool", "test_pool"), "drawn on the surface")
  T.fails(function() T.ui_texts("no_such_surface") end)
end)

T.case("settings: plain data by dotted keys", function()
