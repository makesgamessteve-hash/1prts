-- Lua unit tests: VR settings (comfort options and the video settings in a headset), the
-- options menu's VR page, VR controller names and rebinding them on the controls page.
-- MIT License.
local settings = require("game.settings")
local menu = require("ui.menu")
local options = require("ui.options")
local controls = require("ui.controls")
local glyphs = require("ui.glyphs")

local function reset()
  prts.settings.set("xr", nil)
  prts.settings.set("bindings", nil)
  settings.apply_xr()
end

T.case("VR settings: comfort defaults, saved values over them, applied to the engine", function()
  reset()
  local x, v = settings.xr(), settings.xr_video()
  T.eq(x.locomotion, "smooth")
  T.eq(x.turn, "snap")
  T.eq(x.vignette, true)
  T.eq(x.seated, false)
  T.eq(v.snap, false)
  T.eq(v.preset, "hd")
  local applied = settings.apply_xr()
  T.eq(applied.snap, false, "the engine draws VR without vertex snapping")
  T.eq(applied.dither, false)
  T.eq(applied.vignette, true)
  T.eq(applied.preset, "hd")
  prts.settings.set("xr.vignette", false)
  prts.settings.set("xr.locomotion", 3) -- a wrong type is ignored
  T.eq(settings.xr().vignette, false)
  T.eq(settings.xr().locomotion, "smooth")
  settings.set_xr("snap", true, false, true)
  T.eq(prts.xr.settings().snap, true)
  T.eq(prts.settings.get("xr.video.snap"), true)
  T.eq(prts.render.settings().snap, true, "the flat screen keeps its own setting")
  reset()
  T.eq(prts.xr.settings().snap, false)
end)

T.case("prts.xr checks its values and reports the session", function()
  T.fails(function() prts.xr.settings{ locomotion = "fly" } end, "unknown locomotion")
  T.fails(function() prts.xr.settings{ turn = 3 } end, "unknown turning")
  T.fails(function() prts.xr.settings{ snap_angle = "big" } end, "not a number")
  T.fails(function() prts.xr.settings{ preset = "huge" } end, "unknown preset")
  T.fails(function() prts.xr.settings{ preset = true } end, "not a preset name")
  local s = prts.xr.settings{ snap_angle = 500, turn_speed = 1, vignette_strength = 2 }
  T.eq(s.snap_angle, 180, "clamped")
  T.eq(s.turn_speed, 10)
  T.eq(s.vignette_strength, 1)
  prts.xr.settings{ vignette_strength = 0.6 }
  settings.apply_xr()
  T.eq(prts.xr.settings().snap_angle, 45)
  local st = prts.xr.state()
  T.eq(st.active, false)
  T.eq(st.pointer, "right")
  T.eq(prts.xr.exit(), false, "no session to leave")
  T.eq(T.xr_view(), nil, "no head outside VR")
  T.fails(function() T.xr_frame{} end, "a frame needs a session")
  T.xr_begin()
  T.xr_frame{ right = { aim = { pos = { 0.2, 1.2, -0.2 }, quat = { 0, 0, 0, 1 } }, grip = { pos = { 0.2, 1.1, -0.1 } } } }
  T.ui_frame()
  st = prts.xr.state()
  T.eq(st.active, true)
  T.eq(st.views, 2)
  T.eq(st.right, true)
  T.eq(st.left, false)
  T.eq(prts.input.scheme(), "xr")
  T.eq(prts.xr.exit(), true, "leaves the session")
  T.ui_frame()
  T.eq(prts.xr.state().active, false)
  T.eq(prts.input.scheme(), "kbm", "the flat page's controls again")
end)

T.case("the options menu's VR page changes and saves the VR settings", function()
  reset()
  menu.open("options")
  T.ui_click("tab.vr")
  T.eq(options.tab, "vr")
  T.is_true(T.ui_has("Comfort vignette while moving"), "comfort options listed")
  T.ui_click("xr.locomotion")
  T.eq(prts.xr.settings().locomotion, "teleport")
  T.eq(prts.settings.get("xr.locomotion"), "teleport", "saved")
  T.ui_click("xr.locomotion")
  T.eq(prts.xr.settings().locomotion, "smooth")
  T.ui_click("xr.snap_angle") -- the middle of the slider
  T.eq(prts.xr.settings().snap_angle % 15, 0, "whole steps")
  T.ui_click("xr.turn")
  T.eq(prts.xr.settings().turn, "smooth")
  T.ui_click("xr.turn_speed")
  T.near(prts.xr.settings().turn_speed, 195, 10)
  T.ui_click("xr.turn")
  T.eq(prts.xr.settings().turn, "snap")
  T.ui_click("xr.preset")
  T.eq(prts.xr.settings().preset, settings.next_preset("hd"))
  T.ui_click("xr.vignette")
  T.eq(prts.xr.settings().vignette, false)
  T.ui_click("xr.seated")
  T.eq(prts.xr.settings().seated, true)
  T.ui_click("xr.video.snap")
  T.eq(prts.xr.settings().snap, true)
  T.eq(prts.render.settings().snap, true, "the flat screen's setting is separate")
  T.ui_click("options.back")
  reset()
  prts.settings.save()
  options.tab = "video"
  menu.open(nil)
end)

T.case("VR controller names, prompts and rebinding with a controller", function()
  T.eq(glyphs.name({ kind = "xr_button", code = 8 }), "Right trigger")
  T.eq(glyphs.name({ kind = "xr_button", code = 12 }), "A")
  T.eq(glyphs.name({ kind = "xr_button", code = 5 }), "Y")
  T.eq(glyphs.name({ kind = "xr_button", code = 1 }), "Left grip")
  T.eq(glyphs.name({ kind = "xr_button", code = 15 }), "Right button 7")
  T.eq(glyphs.name({ kind = "xr_axis", code = 3 }), "Left stick")
  T.eq(glyphs.name({ kind = "xr_axis", code = 6 }), "Right stick")
  T.eq(glyphs.prompt("use", "xr"), "(Right trigger)")
  T.eq(glyphs.list("teleport", "xr"), "Left stick")
  T.eq(glyphs.list("teleport", "kbm"), "none")
  -- the controls page takes the next VR controller button or stick as the binding
  menu.open("options")
  T.ui_click("tab.controls")
  T.ui_click("scheme.xr")
  T.eq(controls.scheme, "xr")
  T.ui_click("rebind.run")
  T.eq(controls.capturing, "run")
  T.xr_begin()
  T.xr_frame{ right = { squeeze = 1 } }
  T.ui_frame()
  T.eq(controls.capturing, nil)
  T.eq(glyphs.list("run", "xr"), "Right grip")
  T.eq(prts.settings.get("bindings.xr.run").xr_buttons[1], 9, "override stored")
  T.xr_frame{}
  T.ui_click("rebind.crouch")
  T.xr_frame{ left = { axes = { 0, 0, -0.9, 0 } } }
  T.ui_frame()
  T.eq(glyphs.list("crouch", "xr"), "Left stick")
  T.eq(prts.settings.get("bindings.xr.crouch").xr_axes[1].scale, -1)
  T.xr_end()
  T.ui_click("controls.reset")
  T.eq(glyphs.list("run", "xr"), "Left stick press")
  T.eq(glyphs.list("crouch", "xr"), "B")
  T.ui_click("options.back")
  reset()
  menu.open(nil)
end)
