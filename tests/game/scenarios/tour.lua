-- A guided look around the Proving Ground that saves screenshots (when run with a window,
-- for example: 1stprts --hidden --size 1920x1080 --scenario tests/game/scenarios/tour.lua --out shots).
-- Headless, the screenshots are skipped and the tour is a smoke test of the routes.
return {
  name = "Proving Ground tour",
  max_seconds = 90,
  run = function(t)
    local c = t.commander()
    t.place("start", 0.05)
    t.ticks(3)
    t.screenshot("01_approach_at_dusk")
    -- Harrowmark from the road, far to the south
    local hx, hz = -14, 290
    t.place(hx, prts.scene.height(hx, hz), hz, math.atan(hx, hz), 0.04)
    t.ticks(3)
    t.screenshot("02_harrowmark_from_afar")
    t.place("keep_door")
    t.face("keep.door", 1.1, 1.6, 0)
    t.input.press("use")
    t.ticks(40)
    t.look(0, 0)
    t.screenshot("03_open_door")
    t.place("hall_view", -0.05)
    t.ticks(3)
    t.screenshot("04_great_hall")
    t.place("forge_door")
    t.face("keep.forge.door", 0.6, 1.4, 0)
    t.input.press("use")
    t.ticks(40)
    t.place(-6.0, 0.2, -5.0)
    t.face(-9.7, 1.0, -8.2)
    t.ticks(3)
    t.screenshot("05_forge")
    t.place("stair_base", 0.15)
    t.ticks(3)
    t.screenshot("06_stairs")
    t.place("war_room_view", -0.38)
    t.ticks(3)
    t.screenshot("07_war_room")
    t.place(-1.4, 9.2, 5.0, -0.25, -0.62)
    t.ticks(3)
    t.screenshot("08_war_table_illusion")
    t.place(0, 13.7, 8.4, 0, -0.05)
    t.look(math.pi, -0.08)
    t.ticks(3)
    t.screenshot("09_battlements")
    t.expect(t.in_zone(c, "keep.great_hall"), "on the roof, not in the hall").equals(false)
    t.place(-1.2, 0, 15.2)
    t.face("npc.door_guard", 0, 1.3, 0)
    t.ticks(3)
    t.screenshot("10_door_guard")
    t.place(-1.5, 0.2, 3.0)
    t.face("npc.hall_guard", 0, 1.2, 0)
    t.ticks(3)
    t.screenshot("11_hall_guard")
    t.place(4.6, 0.2, 5.8)
    t.face(-0.6, 0.6, -0.6)
    t.ticks(3)
    t.screenshot("12_hall_benches_braziers")
    -- the castle: the Outer Ward before the Lion Gate, the inner wall-walk, the Raven Tower's top
    t.place("outer_ward", 0.12)
    t.ticks(3)
    t.screenshot("18_outer_ward")
    t.place(-30, 15, 41.2, -math.pi / 2, -0.05)
    t.ticks(3)
    t.screenshot("19_wall_walk")
    -- on the wall top, at a crenel (the gaps are on the odd sides of the 16-sided tower)
    local a = 5 * 2 * math.pi / 16
    t.place(math.cos(a) * 7.9, 36, -53 + math.sin(a) * 7.9, math.atan(-math.cos(a), -math.sin(a)) + math.pi, -0.42)
    t.ticks(3)
    t.screenshot("20_raven_tower_view")
    t.place(-32, 0, -34, math.atan(-32, -34), 0.12)
    t.ticks(3)
    t.screenshot("21_inner_ward")
    t.place(-6, 0, 135, math.atan(6, 135 - 106), 0.14)
    t.ticks(3)
    t.screenshot("22_kings_gate")
  end,
}
